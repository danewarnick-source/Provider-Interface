import { forwardRef, type ButtonHTMLAttributes, type HTMLAttributes, type ReactNode } from "react";
import { Sparkles, Loader2 } from "lucide-react";
import { PiMark } from "@/components/pi-landing/pi-mark";

/**
 * Single source of truth for the NECTAR visual signature.
 *
 * Denim tokens:
 *   mark tile     deep (--denim-deep) with green accent bars
 *   callouts      info style — bg pt / border pt2 / text pri
 *   accent        acc / accd (green) — never gold
 *
 * Use these components anywhere NECTAR generates, summarizes,
 * suggests, or assists so the brand reads instantly.
 */

const cn = (...c: Array<string | false | null | undefined>) => c.filter(Boolean).join(" ");

/* -------------------------------------------------------------------------- */
/* NectarMark — circular hexagon+sparkle avatar (the "face" of NECTAR)        */
/* -------------------------------------------------------------------------- */

export function NectarMark({
  size = "md",
  className,
  ornament = true,
}: {
  size?: "sm" | "md" | "lg";
  className?: string;
  /** Green sparkle badge. Off on staff phone so it is not read as a pin. */
  ornament?: boolean;
}) {
  const dims = size === "sm" ? "h-7 w-7" : size === "lg" ? "h-16 w-16" : "h-10 w-10";
  const hex = size === "sm" ? "h-4 w-4" : size === "lg" ? "h-9 w-9" : "h-5 w-5";
  const spark = size === "sm" ? "h-2 w-2" : size === "lg" ? "h-3.5 w-3.5" : "h-2.5 w-2.5";
  return (
    <span
      aria-hidden
      className={cn(
        "relative inline-flex shrink-0 items-center justify-center rounded-full",
        "bg-deep text-acc ring-1 ring-pri/20 shadow-[var(--denim-shadow-sm)]",
        dims,
        className,
      )}
    >
      <PiMark className={cn(hex)} />
      {ornament ? (
        <span className="absolute -right-0.5 -top-0.5 inline-flex items-center justify-center rounded-full bg-acc p-[2px] text-white ring-2 ring-paper">
          <Sparkles className={spark} strokeWidth={2.5} />
        </span>
      ) : null}
    </span>
  );
}

/* -------------------------------------------------------------------------- */
/* NectarBadge — pill wordmark "✨ NECTAR" (info pill), the recognizable tag */
/* -------------------------------------------------------------------------- */

export function NectarBadge({
  size = "md",
  live = false,
  label = "Nectar",
  className,
}: {
  size?: "xs" | "sm" | "md";
  live?: boolean;
  label?: string;
  className?: string;
}) {
  const pad =
    size === "xs"
      ? "px-2 py-0.5 text-[9px]"
      : size === "sm"
      ? "px-2.5 py-1 text-[10px]"
      : "px-3 py-1 text-[11px]";
  const ic = size === "xs" ? "h-2.5 w-2.5" : "h-3 w-3";
  return (
    <span
      className={cn(
        "inline-flex items-center gap-1.5 rounded-full border border-pt2 bg-pt",
        "font-semibold uppercase tracking-wider text-pri",
        pad,
        className,
      )}
    >
      <Sparkles className={ic} strokeWidth={2.5} />
      <span>{label}</span>
      {live && (
        <span className="ml-1 inline-flex items-center gap-1 text-deep/80">
          <span className="relative inline-flex h-1.5 w-1.5">
            <span className="absolute inline-flex h-full w-full animate-ping rounded-full bg-accd opacity-70" />
            <span className="relative inline-flex h-1.5 w-1.5 rounded-full bg-acc" />
          </span>
          <span className="text-[9px] font-bold uppercase tracking-wider">live</span>
        </span>
      )}
    </span>
  );
}

/* -------------------------------------------------------------------------- */
/* NectarChip — subtle inline tag for "NECTAR-generated" annotations          */
/* -------------------------------------------------------------------------- */

