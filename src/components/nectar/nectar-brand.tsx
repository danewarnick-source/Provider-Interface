/* -------------------------------------------------------------------------- */
/* NectarSurface — the navy Denim band NECTAR header sections sit on       */
/* -------------------------------------------------------------------------- */

export const NectarSurface = forwardRef<HTMLDivElement, HTMLAttributes<HTMLDivElement>>(
  function NectarSurface({ className, children, ...rest }, ref) {
    return (
      <div
        ref={ref}
        {...rest}
        className={cn(
          "denim-band rounded-[24px] text-white",
          className,
        )}
      >
        {children}
      </div>
    );
  },
);

/* -------------------------------------------------------------------------- */
/* NectarCard — light variant for in-flow cards (Billing alerts, etc.)        */
/* -------------------------------------------------------------------------- */

export function NectarCard({
  className,
  children,
  ...rest
}: HTMLAttributes<HTMLDivElement>) {
  return (
    <div
      {...rest}
      className={cn(
        "relative overflow-hidden rounded-[var(--denim-r)] border border-pt2 bg-card shadow-[var(--denim-shadow-sm)]",
        "before:absolute before:inset-y-0 before:left-0 before:w-1 before:bg-acc",
        className,
      )}
    >
      {children}
    </div>
  );
}

/* -------------------------------------------------------------------------- */
/* NectarHeader — branded section header (mark + title + NECTAR badge)        */
/* -------------------------------------------------------------------------- */

export function NectarHeader({
  title,
  eyebrow,
  description,
  markSize = "md",
  surface = "navy",
  right,
  className,
}: {
  title: ReactNode;
  eyebrow?: ReactNode;
  description?: ReactNode;
  markSize?: "sm" | "md" | "lg";
  /** "navy" = Denim navy band header; "light" = light card header */
  surface?: "navy" | "light";
  right?: ReactNode;
  className?: string;
}) {
  if (surface === "navy") {
    return (
      <NectarSurface className={cn("p-5", className)}>
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div className="flex items-center gap-3">
            <NectarMark size={markSize} />
            <div className="min-w-0">
              <div className="flex items-center gap-2">
                <NectarBadge size="xs" />
                {eyebrow && (
                  <span className="text-[10px] font-semibold uppercase tracking-[0.1em] text-accl">
                    {eyebrow}
                  </span>
                )}
              </div>
              <h2 className="mt-1 font-display text-lg font-bold tracking-[-0.01em] text-white">
                {title}
              </h2>
              {description && (
                <p className="mt-0.5 text-sm text-ondark">{description}</p>
              )}
            </div>
          </div>
          {right}
        </div>
      </NectarSurface>
    );
  }
  return (
    <div className={cn("flex flex-wrap items-center justify-between gap-3", className)}>
      <div className="flex items-center gap-3">
        <NectarMark size={markSize} />
        <div className="min-w-0">
          <div className="flex items-center gap-2">
            <NectarBadge size="xs" />
            {eyebrow && (
              <span className="text-[10px] font-semibold uppercase tracking-[0.1em] text-accd">
                {eyebrow}
              </span>
            )}
          </div>
          <h2 className="mt-1 font-display text-lg font-semibold tracking-[-0.01em] text-deep">
            {title}
          </h2>
          {description && (
            <p className="mt-0.5 text-sm text-muted-foreground">{description}</p>
          )}
        </div>
      </div>
      {right}
    </div>
  );
}

/* -------------------------------------------------------------------------- */
/* NectarButton — the canonical "Ask NECTAR" / "Run with NECTAR" CTA          */
/* -------------------------------------------------------------------------- */

type NectarButtonProps = ButtonHTMLAttributes<HTMLButtonElement> & {
  variant?: "primary" | "accent" | "ghost";
  loading?: boolean;
  icon?: ReactNode;
};

export const NectarButton = forwardRef<HTMLButtonElement, NectarButtonProps>(
  function NectarButton(
    { variant = "primary", loading, icon, children, className, disabled, ...rest },
    ref,
  ) {
    const base =
      "inline-flex min-h-[40px] items-center justify-center gap-2 rounded-full px-4 py-2 text-sm font-semibold shadow-[var(--denim-shadow-sm)] transition disabled:opacity-50 disabled:cursor-not-allowed focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-pri/30 focus-visible:ring-offset-2";
    const styles =
      variant === "accent"
        ? "bg-[var(--hive-primary)] text-[var(--hive-primary-fg)] hover:bg-[var(--hive-primary-hover)]"
        : variant === "ghost"
        ? "border border-acctb bg-acct text-accd hover:bg-acclh"
        : "bg-[var(--hive-primary)] text-[var(--hive-primary-fg)] hover:bg-[var(--hive-primary-hover)]";
    const leading = loading ? (
      <Loader2 className="h-4 w-4 animate-spin" />
    ) : (
      icon ?? <Sparkles className="h-4 w-4" strokeWidth={2.5} />
    );
    return (
      <button
        ref={ref}
        {...rest}
        disabled={disabled || loading}
        className={cn(base, styles, className)}
      >
        {leading}
        {children}
      </button>
    );
  },
);
